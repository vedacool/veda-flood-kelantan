"""Generate docs/CODEMAP.md: every VEDA module -> purpose, public functions/classes, who imports it.

Usage:
    python scripts/codemap.py           # rewrite docs/CODEMAP.md
    python scripts/codemap.py --check   # exit 1 if docs/CODEMAP.md is out of date

Standard library only (ast), so it runs offline and in the pre-commit hook.
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODEMAP.md"
SCAN = ["app", "scripts", "run.py"]  # spikes/ is throwaway exploration code — listed, not mapped


def first_line(doc):
    """First line of a docstring, or a placeholder."""
    return (doc or "").strip().splitlines()[0].strip() if (doc or "").strip() else "_(no docstring)_"


def module_name(path):
    """Dotted module name for a file path (package __init__ -> package)."""
    rel = path.relative_to(ROOT).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def python_files():
    """All .py files under the scanned roots."""
    files = []
    for entry in SCAN:
        p = ROOT / entry
        if p.is_file():
            files.append(p)
        elif p.is_dir():
            files.extend(sorted(p.rglob("*.py")))
    return [f for f in files if "__pycache__" not in f.parts]


def imported_modules(tree, this_module, is_package=False):
    """Absolute names of modules this file imports (relative imports resolved).
    A package's __init__ is its own package, so `from . import x` there means this_module.x."""
    names = set()
    pkg = this_module.split(".") if is_package else this_module.split(".")[:-1]
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(a.name for a in node.names)
        elif isinstance(node, ast.ImportFrom):
            base = node.module or ""
            if node.level:
                anchor = pkg[: len(pkg) - (node.level - 1)]
                base = ".".join(anchor + ([base] if base else []))
            names.add(base)
            names.update(f"{base}.{a.name}" for a in node.names)
    return names


def imports_of_file(path):
    """Imported module names of one .py file under ROOT (shared with tests/test_architecture.py)."""
    tree = ast.parse(Path(path).read_text(encoding="utf-8"), filename=str(path))
    return imported_modules(tree, module_name(Path(path)), is_package=Path(path).name == "__init__.py")


def build():
    """Parse every module and render the CODEMAP markdown text."""
    modules = {}
    for f in python_files():
        tree = ast.parse(f.read_text(encoding="utf-8"), filename=str(f))
        name = module_name(f)
        public = []
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and not node.name.startswith("_"):
                kind = "class" if isinstance(node, ast.ClassDef) else "def"
                args = "" if kind == "class" else "(" + ", ".join(a.arg for a in node.args.args) + ")"
                public.append(f"`{kind} {node.name}{args}` — {first_line(ast.get_docstring(node))}")
        modules[name] = {"path": f.relative_to(ROOT).as_posix(), "purpose": first_line(ast.get_docstring(tree)),
                         "public": public, "imports": imported_modules(tree, name, f.name == "__init__.py")}

    for name, m in modules.items():
        m["callers"] = sorted(other for other, o in modules.items() if other != name and name in o["imports"])

    lines = ["# CODEMAP — generated, do not edit by hand",
             "_Regenerated by `python scripts/codemap.py` (runs in the pre-commit hook). "
             "Purpose = module docstring; callers = modules that import it._", ""]
    if not modules:
        lines.append("_No modules yet._")
    for name in sorted(modules):
        m = modules[name]
        lines += [f"## `{name}` — [{m['path']}](../{m['path']})", f"**Purpose:** {m['purpose']}  "]
        lines.append(f"**Called by:** {', '.join(f'`{c}`' for c in m['callers']) or '—'}")
        lines += [f"- {p}" for p in m["public"]] or ["- _(no public functions)_"]
        lines.append("")
    spikes = sorted(p.name for p in (ROOT / "spikes").glob("s*.py")) if (ROOT / "spikes").is_dir() else []
    if spikes:
        lines += ["## Not mapped", f"- `spikes/` — B-64 throwaway exploration scripts ({', '.join(spikes)}). Not VEDA code.", ""]
    return "\n".join(lines)


def main():
    """Write docs/CODEMAP.md, or with --check fail if it is stale."""
    text = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in sys.argv:
        if current != text:
            print("docs/CODEMAP.md is out of date - run: python scripts/codemap.py")
            return 1
        return 0
    if current != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print("docs/CODEMAP.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
